/** Spending scenario: one P2MR output funded, spent by a one-input transaction. */
struct Spend {
    P2MRTree tree;
    CTxOut spent;
    CMutableTransaction tx;

    explicit Spend(P2MRTree t) : tree(std::move(t))
    {
        spent = CTxOut{50 * COIN, tree.ScriptPubKey()};
        tx.version = 2;
        tx.vin.emplace_back(COutPoint{Txid::FromUint256(uint256::ONE), 0});
        tx.vout.emplace_back(49 * COIN, tree.ScriptPubKey());
    }

    uint256 SigHash(size_t leaf, PQAlgorithm algo, uint8_t hash_type = SIGHASH_DEFAULT) const
    {
        return LeafSigHash(tx, 0, {spent}, tree.LeafHash(leaf), hash_type, static_cast<uint8_t>(algo));
    }
    uint256 SchnorrSigHash(size_t leaf) const
    {
        return LeafSigHash(tx, 0, {spent}, tree.LeafHash(leaf), SIGHASH_DEFAULT, /*key_version=*/0);
    }

    /** Witness = items (bottom to top), then the leaf script and its control block. */
    void SetWitness(size_t leaf, std::vector<std::vector<unsigned char>> items)
    {
        items.emplace_back(tree.leaves.at(leaf).begin(), tree.leaves.at(leaf).end());
        items.push_back(tree.Control(leaf));
        tx.vin[0].scriptWitness.stack = std::move(items);
    }

    ScriptError Verify(script_verify_flags flags = SCRIPT_VERIFY_P2SH | SCRIPT_VERIFY_WITNESS | SCRIPT_VERIFY_TAPROOT | SCRIPT_VERIFY_P2MR) const
    {
        PrecomputedTransactionData txdata;
        txdata.Init(tx, std::vector<CTxOut>{spent});
        MutableTransactionSignatureChecker checker(&tx, 0, spent.nValue, txdata, MissingDataBehavior::ASSERT_FAIL);
        ScriptError err;
        const bool ok{VerifyScript(tx.vin[0].scriptSig, spent.scriptPubKey, &tx.vin[0].scriptWitness, flags, checker, &err)};
        BOOST_CHECK_EQUAL(ok, err == SCRIPT_ERR_OK);
        return err;
    }
};

CKey SchnorrKey(uint8_t tag)
{
    std::array<unsigned char, 32> secret{};
    secret.fill(tag);
    CKey key;
    key.Set(secret.begin(), secret.end(), true);
    return key;
}

std::vector<unsigned char> SignSchnorr(const CKey& key, const uint256& sighash)
{
    std::vector<unsigned char> sig(64);
    BOOST_REQUIRE(key.SignSchnorr(sighash, sig, /*merkle_root=*/nullptr, uint256::ZERO));
    return sig;
}

std::vector<unsigned char> XOnly(const CKey& key)
{
    const XOnlyPubKey xonly{key.GetPubKey()};
    return {xonly.begin(), xonly.end()};
}

