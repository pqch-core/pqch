BOOST_AUTO_TEST_CASE(pq_validation_budget)
{
    // Each input may only spend validation weight up to its witness size + 50. Re-checking the same
    // ML-DSA signature many times with OP_2DUP exhausts it.
    const auto key{MLDSAKey(6)};
    CScript leaf;
    const int checks{40};
    for (int i = 0; i < checks; ++i) leaf << OP_2DUP << OP_CHECKSIGMLDSAVERIFY;
    leaf << OP_2DROP << OP_TRUE;
    Spend s{MakeTree({leaf})};
    s.SetWitness(0, {SignMLDSA(key.seckey, s.SigHash(0, PQAlgorithm::ML_DSA_44)), key.pubkey});
    const int64_t budget{int64_t(::GetSerializeSize(s.tx.vin[0].scriptWitness.stack)) + VALIDATION_WEIGHT_OFFSET};
    BOOST_REQUIRE(checks * VALIDATION_WEIGHT_PER_MLDSA_SIGOP > budget);
    CHECK_ERR(s.Verify(), SCRIPT_ERR_TAPSCRIPT_VALIDATION_WEIGHT);

    // Within budget it is fine.
    CScript small;
    const int few{int(budget / VALIDATION_WEIGHT_PER_MLDSA_SIGOP) - 2};
    BOOST_REQUIRE(few > 0);
    for (int i = 0; i < few; ++i) small << OP_2DUP << OP_CHECKSIGMLDSAVERIFY;
    small << OP_2DROP << OP_TRUE;
    Spend ok{MakeTree({small})};
    ok.SetWitness(0, {SignMLDSA(key.seckey, ok.SigHash(0, PQAlgorithm::ML_DSA_44)), key.pubkey});
    CHECK_ERR(ok.Verify(), SCRIPT_ERR_OK);
}

BOOST_AUTO_TEST_CASE(pq_output_rule)
{
    const auto p2mr{MakeTree({LeafMLDSA(MLDSAKey(1).pubkey)}).ScriptPubKey()};
    BOOST_CHECK(Consensus::IsPQAllowedOutput(p2mr));
    BOOST_CHECK(Consensus::IsPQAllowedOutput(CScript() << OP_RETURN << std::vector<unsigned char>{1, 2, 3}));
    BOOST_CHECK(Consensus::IsPQAllowedOutput(CScript() << OP_RETURN));
    BOOST_CHECK(Consensus::IsPQAllowedOutput(CScript() << OP_1 << std::vector<unsigned char>{0x4e, 0x73})); // pay-to-anchor
    BOOST_CHECK(Consensus::IsPQAllowedOutput(CScript() << OP_2 << std::vector<unsigned char>(32, 7)));     // future version
    BOOST_CHECK(Consensus::IsPQAllowedOutput(CScript() << OP_16 << std::vector<unsigned char>(40, 7)));

    const CKey ec{SchnorrKey(9)};
    const auto pubkey{ToByteVector(ec.GetPubKey())};
    const std::vector<unsigned char> h20(20, 1), h32(32, 1);
    BOOST_CHECK(!Consensus::IsPQAllowedOutput(CScript()));
    BOOST_CHECK(!Consensus::IsPQAllowedOutput(CScript() << pubkey << OP_CHECKSIG));                                   // P2PK
    BOOST_CHECK(!Consensus::IsPQAllowedOutput(CScript() << OP_DUP << OP_HASH160 << h20 << OP_EQUALVERIFY << OP_CHECKSIG)); // P2PKH
    BOOST_CHECK(!Consensus::IsPQAllowedOutput(CScript() << OP_HASH160 << h20 << OP_EQUAL));                           // P2SH
    BOOST_CHECK(!Consensus::IsPQAllowedOutput(CScript() << OP_0 << h20));                                             // P2WPKH
    BOOST_CHECK(!Consensus::IsPQAllowedOutput(CScript() << OP_0 << h32));                                             // P2WSH
    BOOST_CHECK(!Consensus::IsPQAllowedOutput(CScript() << OP_1 << h20));                                             // v1, other size
    BOOST_CHECK(!Consensus::IsPQAllowedOutput(CScript() << OP_TRUE));                                                 // bare script

    CMutableTransaction tx;
    tx.vout.emplace_back(1 * COIN, p2mr);
    TxValidationState state;
    BOOST_CHECK(Consensus::CheckPQOutputs(CTransaction{tx}, state));
    tx.vout.emplace_back(1 * COIN, CScript() << OP_0 << h20);
    BOOST_CHECK(!Consensus::CheckPQOutputs(CTransaction{tx}, state));
    BOOST_CHECK_EQUAL(state.GetRejectReason(), "bad-txns-output-not-pq");
}

