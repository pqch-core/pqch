BOOST_AUTO_TEST_CASE(mldsa_reference_vectors)
{
    for (const auto& v : MLDSA_VECTORS) {
        pqc::KeyPair key;
        BOOST_REQUIRE(pqc::MLDSA44KeyFromSeed(Seed(v.tag), key));
        BOOST_CHECK_EQUAL(key.pubkey.size(), pqc::MLDSA44_PUBKEY_SIZE);
        BOOST_CHECK_EQUAL(Sha256Hex(key.pubkey), v.pubkey_sha256);
        const auto msg{ParseHex(v.msg)};
        std::vector<unsigned char> sig;
        BOOST_REQUIRE(pqc::MLDSA44Sign(key.seckey, msg, pqc::TX_SIGNATURE_CONTEXT, ZERO_RND, sig));
        BOOST_CHECK_EQUAL(sig.size(), pqc::MLDSA44_SIG_SIZE);
        // Same bytes as the independent implementation: it verifies ours and we verify its.
        BOOST_CHECK_EQUAL(Sha256Hex(sig), v.sig_sha256);
        BOOST_CHECK(pqc::MLDSA44Verify(sig, msg, pqc::TX_SIGNATURE_CONTEXT, key.pubkey));
    }
}

