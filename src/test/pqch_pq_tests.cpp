BOOST_AUTO_TEST_CASE(p2mr_mldsa_leaf)
{
    const auto key{MLDSAKey(1)};
    Spend s{MakeTree({LeafMLDSA(key.pubkey)})};

    s.SetWitness(0, {SignMLDSA(key.seckey, s.SigHash(0, PQAlgorithm::ML_DSA_44))});
    CHECK_ERR(s.Verify(), SCRIPT_ERR_OK);

    // Explicit hash type byte; SIGHASH_DEFAULT may not be explicit (as in BIP 341).
    s.SetWitness(0, {SignMLDSA(key.seckey, s.SigHash(0, PQAlgorithm::ML_DSA_44, SIGHASH_ALL), SIGHASH_ALL)});
    CHECK_ERR(s.Verify(), SCRIPT_ERR_OK);
    auto sig_default{SignMLDSA(key.seckey, s.SigHash(0, PQAlgorithm::ML_DSA_44))};
    sig_default.push_back(SIGHASH_DEFAULT);
    s.SetWitness(0, {sig_default});
    CHECK_ERR(s.Verify(), SCRIPT_ERR_PQ_SIG_HASHTYPE);

    // The signature commits to the outputs.
    s.SetWitness(0, {SignMLDSA(key.seckey, s.SigHash(0, PQAlgorithm::ML_DSA_44))});
    s.tx.vout[0].nValue -= 1;
    CHECK_ERR(s.Verify(), SCRIPT_ERR_PQ_SIG);
    s.tx.vout[0].nValue += 1;

    // The algorithm is part of the signature hash (key_version): a sighash computed as for
    // Schnorr (key_version 0) does not verify.
    s.SetWitness(0, {SignMLDSA(key.seckey, s.SchnorrSigHash(0))});
    CHECK_ERR(s.Verify(), SCRIPT_ERR_PQ_SIG);

    // Wrong signer.
    s.SetWitness(0, {SignMLDSA(MLDSAKey(2).seckey, s.SigHash(0, PQAlgorithm::ML_DSA_44))});
    CHECK_ERR(s.Verify(), SCRIPT_ERR_PQ_SIG);

    // Size errors.
    auto truncated{SignMLDSA(key.seckey, s.SigHash(0, PQAlgorithm::ML_DSA_44))};
    truncated.pop_back();
    s.SetWitness(0, {truncated});
    CHECK_ERR(s.Verify(), SCRIPT_ERR_PQ_SIG_SIZE);

    // Empty signature: OP_CHECKSIGMLDSA pushes false, the script then fails cleanly.
    s.SetWitness(0, {{}});
    CHECK_ERR(s.Verify(), SCRIPT_ERR_EVAL_FALSE);
}

BOOST_AUTO_TEST_CASE(p2mr_hybrid_and_rule2)
{
    const auto pq{MLDSAKey(3)};
    const auto ec{SchnorrKey(3)};
    Spend s{MakeTree({LeafHybrid(XOnly(ec), pq.pubkey)})};

    // Wallet default: both signatures (witness bottom to top: ML-DSA, then Schnorr).
    const auto mldsa_sig{SignMLDSA(pq.seckey, s.SigHash(0, PQAlgorithm::ML_DSA_44))};
    const auto schnorr_sig{SignSchnorr(ec, s.SchnorrSigHash(0))};
    s.SetWitness(0, {mldsa_sig, schnorr_sig});
    CHECK_ERR(s.Verify(), SCRIPT_ERR_OK);

    // A quantum attacker who forges the Schnorr signature still needs the ML-DSA one.
    // (With the ML-DSA signature left empty, rule 2 is what rejects it.)
    s.SetWitness(0, {{}, schnorr_sig});
    CHECK_ERR(s.Verify(), SCRIPT_ERR_PQ_SIG_REQUIRED);
    // And someone who breaks lattices still needs the Schnorr one.
    s.SetWitness(0, {mldsa_sig, std::vector<unsigned char>(64, 0)});
    CHECK_ERR(s.Verify(), SCRIPT_ERR_SCHNORR_SIG);

    // Rule 2: a leaf that checks an elliptic-curve signature without a post-quantum one is invalid.
    Spend ec_only{MakeTree({CScript() << XOnly(ec) << OP_CHECKSIG})};
    ec_only.SetWitness(0, {SignSchnorr(ec, ec_only.SchnorrSigHash(0))});
    CHECK_ERR(ec_only.Verify(), SCRIPT_ERR_PQ_SIG_REQUIRED);

    // Scripts with only hashlocks and timelocks are allowed.
    const std::vector<unsigned char> preimage{'p', 'q', 'c', 'h'};
    uint256 digest;
    CSHA256().Write(preimage.data(), preimage.size()).Finalize(digest.begin());
    Spend hashlock{MakeTree({CScript() << OP_SHA256 << std::vector<unsigned char>(digest.begin(), digest.end()) << OP_EQUAL})};
    hashlock.SetWitness(0, {preimage});
    CHECK_ERR(hashlock.Verify(), SCRIPT_ERR_OK);
}

BOOST_AUTO_TEST_CASE(p2mr_two_leaves_slhdsa_recovery)
{
    const auto daily{MLDSAKey(4)};
    const auto recovery{SLHDSAKey(4)};
    Spend s{MakeTree({LeafMLDSA(daily.pubkey), LeafSLHDSA(recovery.pubkey)})};

    // Leaf A (daily use).
    s.SetWitness(0, {SignMLDSA(daily.seckey, s.SigHash(0, PQAlgorithm::ML_DSA_44))});
    CHECK_ERR(s.Verify(), SCRIPT_ERR_OK);

    // Leaf B (recovery, hash-based signature).
    const auto slh_sig{SignSLHDSA(recovery.seckey, s.SigHash(1, PQAlgorithm::SLH_DSA_SHA2_128S))};
    s.SetWitness(1, {slh_sig});
    CHECK_ERR(s.Verify(), SCRIPT_ERR_OK);

    // A signature for one leaf does not work in the other (the leaf hash is signed).
    s.SetWitness(1, {SignSLHDSA(recovery.seckey, s.SigHash(0, PQAlgorithm::SLH_DSA_SHA2_128S))});
    CHECK_ERR(s.Verify(), SCRIPT_ERR_PQ_SIG);

    // Wrong Merkle path.
    s.SetWitness(1, {slh_sig});
    s.tx.vin[0].scriptWitness.stack.back()[5] ^= 1;
    CHECK_ERR(s.Verify(), SCRIPT_ERR_WITNESS_PROGRAM_MISMATCH);

    // An ML-DSA key with the SLH-DSA opcode has the wrong size.
    Spend wrong{MakeTree({CScript() << daily.pubkey << OP_CHECKSIGSLHDSA})};
    wrong.SetWitness(0, {slh_sig});
    CHECK_ERR(wrong.Verify(), SCRIPT_ERR_PQ_PUBKEY_SIZE);
}

BOOST_AUTO_TEST_CASE(p2mr_structure)
{
    const auto key{MLDSAKey(5)};
    Spend s{MakeTree({LeafMLDSA(key.pubkey)})};
    const auto sig{SignMLDSA(key.seckey, s.SigHash(0, PQAlgorithm::ML_DSA_44))};

    // No key path: a single witness element (as a Taproot key-path spend would be) is refused.
    s.tx.vin[0].scriptWitness.stack = {std::vector<unsigned char>(64, 1)};
    CHECK_ERR(s.Verify(), SCRIPT_ERR_P2MR_KEY_PATH);

    // Control block: low bit must be set; length must be 1 + 32k.
    s.SetWitness(0, {sig});
    s.tx.vin[0].scriptWitness.stack.back()[0] = P2MR_LEAF_PQSCRIPT;
    CHECK_ERR(s.Verify(), SCRIPT_ERR_P2MR_CONTROL_BYTE);
    s.SetWitness(0, {sig});
    s.tx.vin[0].scriptWitness.stack.back().push_back(0);
    CHECK_ERR(s.Verify(), SCRIPT_ERR_TAPROOT_WRONG_CONTROL_SIZE);

    // Leaf version 0xc0 (plain tapscript, Schnorr only) is refused in P2MR.
    Spend tapscript{MakeTree({LeafMLDSA(key.pubkey)}, TAPROOT_LEAF_TAPSCRIPT)};
    tapscript.SetWitness(0, {sig});
    CHECK_ERR(tapscript.Verify(), SCRIPT_ERR_P2MR_TAPSCRIPT_LEAF);

    // Unknown leaf versions are reserved for soft forks: valid by consensus, refused by policy.
    Spend future{MakeTree({CScript() << OP_TRUE}, 0xc4)};
    future.SetWitness(0, {});
    CHECK_ERR(future.Verify(), SCRIPT_ERR_OK);
    CHECK_ERR(future.Verify(SCRIPT_VERIFY_P2SH | SCRIPT_VERIFY_WITNESS | SCRIPT_VERIFY_P2MR | SCRIPT_VERIFY_DISCOURAGE_UPGRADABLE_TAPROOT_VERSION),
              SCRIPT_ERR_DISCOURAGE_UPGRADABLE_TAPROOT_VERSION);

    // The FN-DSA opcode numbers (0xc4, 0xc5) are still OP_SUCCESS: reserved for a soft fork.
    Spend fndsa{MakeTree({CScript() << OP_0 << static_cast<opcodetype>(0xc4)})};
    fndsa.SetWitness(0, {});
    CHECK_ERR(fndsa.Verify(), SCRIPT_ERR_OK);
    CHECK_ERR(fndsa.Verify(SCRIPT_VERIFY_P2SH | SCRIPT_VERIFY_WITNESS | SCRIPT_VERIFY_P2MR | SCRIPT_VERIFY_DISCOURAGE_OP_SUCCESS),
              SCRIPT_ERR_DISCOURAGE_OP_SUCCESS);

    // Without the P2MR flag the same witness is read as Taproot and fails: the flag decides.
    s.SetWitness(0, {sig});
    CHECK_ERR(s.Verify(), SCRIPT_ERR_OK);
    BOOST_CHECK(s.Verify(SCRIPT_VERIFY_P2SH | SCRIPT_VERIFY_WITNESS | SCRIPT_VERIFY_TAPROOT) != SCRIPT_ERR_OK);
}

