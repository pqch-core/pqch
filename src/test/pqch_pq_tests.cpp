BOOST_AUTO_TEST_CASE(pq_verify_is_strict)
{
    const auto mk{MLDSAKey(7)};
    const auto sk{SLHDSAKey(7)};
    const std::vector<unsigned char> msg(32, 0x42);
    std::vector<unsigned char> msig, ssig;
    BOOST_REQUIRE(pqc::MLDSA44Sign(mk.seckey, msg, pqc::TX_SIGNATURE_CONTEXT, ZERO_RND, msig));
    BOOST_REQUIRE(pqc::SLHDSA128sSign(sk.seckey, msg, pqc::TX_SIGNATURE_CONTEXT, {}, ssig));
    BOOST_CHECK(pqc::MLDSA44Verify(msig, msg, pqc::TX_SIGNATURE_CONTEXT, mk.pubkey));
    BOOST_CHECK(pqc::SLHDSA128sVerify(ssig, msg, pqc::TX_SIGNATURE_CONTEXT, sk.pubkey));

    // Hedged (randomized) ML-DSA signing gives a different, equally valid signature.
    std::vector<unsigned char> msig2;
    const std::vector<unsigned char> rnd(32, 0x99);
    BOOST_REQUIRE(pqc::MLDSA44Sign(mk.seckey, msg, pqc::TX_SIGNATURE_CONTEXT, rnd, msig2));
    BOOST_CHECK(msig2 != msig);
    BOOST_CHECK(pqc::MLDSA44Verify(msig2, msg, pqc::TX_SIGNATURE_CONTEXT, mk.pubkey));

    // Other message, other context (domain separation), other key.
    const std::vector<unsigned char> msg2(32, 0x43);
    const std::vector<unsigned char> other_ctx{'P', 'Q', 'C', 'H', '/', 'x'};
    BOOST_CHECK(!pqc::MLDSA44Verify(msig, msg2, pqc::TX_SIGNATURE_CONTEXT, mk.pubkey));
    BOOST_CHECK(!pqc::MLDSA44Verify(msig, msg, other_ctx, mk.pubkey));
    BOOST_CHECK(!pqc::MLDSA44Verify(msig, msg, pqc::TX_SIGNATURE_CONTEXT, MLDSAKey(8).pubkey));
    BOOST_CHECK(!pqc::SLHDSA128sVerify(ssig, msg2, pqc::TX_SIGNATURE_CONTEXT, sk.pubkey));
    BOOST_CHECK(!pqc::SLHDSA128sVerify(ssig, msg, other_ctx, sk.pubkey));

    // Every single-bit change of the signature is rejected (sampled positions, including the hints).
    for (size_t pos : {size_t{0}, size_t{31}, size_t{1000}, pqc::MLDSA44_SIG_SIZE - 85, pqc::MLDSA44_SIG_SIZE - 1}) {
        auto bad{msig};
        bad[pos] ^= 0x01;
        BOOST_CHECK(!pqc::MLDSA44Verify(bad, msg, pqc::TX_SIGNATURE_CONTEXT, mk.pubkey));
    }
    for (size_t pos : {size_t{0}, size_t{16}, size_t{4000}, pqc::SLHDSA128S_SIG_SIZE - 1}) {
        auto bad{ssig};
        bad[pos] ^= 0x80;
        BOOST_CHECK(!pqc::SLHDSA128sVerify(bad, msg, pqc::TX_SIGNATURE_CONTEXT, sk.pubkey));
    }

    // Wrong lengths: never accepted, never read out of bounds.
    auto longer{msig};
    longer.push_back(0);
    auto shorter{msig};
    shorter.pop_back();
    BOOST_CHECK(!pqc::MLDSA44Verify(longer, msg, pqc::TX_SIGNATURE_CONTEXT, mk.pubkey));
    BOOST_CHECK(!pqc::MLDSA44Verify(shorter, msg, pqc::TX_SIGNATURE_CONTEXT, mk.pubkey));
    BOOST_CHECK(!pqc::MLDSA44Verify({}, msg, pqc::TX_SIGNATURE_CONTEXT, mk.pubkey));
    auto pk_short{mk.pubkey};
    pk_short.pop_back();
    BOOST_CHECK(!pqc::MLDSA44Verify(msig, msg, pqc::TX_SIGNATURE_CONTEXT, pk_short));
    auto slh_long{ssig};
    slh_long.push_back(0);
    BOOST_CHECK(!pqc::SLHDSA128sVerify(slh_long, msg, pqc::TX_SIGNATURE_CONTEXT, sk.pubkey));
    BOOST_CHECK(!pqc::SLHDSA128sVerify(ssig, msg, pqc::TX_SIGNATURE_CONTEXT, std::vector<unsigned char>(31, 0)));

    // ML-DSA hint encoding must be canonical (FIPS 204, Algorithm 21): the last 4 bytes of the hint
    // field count the hints per polynomial and must be non-decreasing and at most omega = 80.
    auto bad_hint{msig};
    bad_hint[pqc::MLDSA44_SIG_SIZE - 1] = 0xff;
    BOOST_CHECK(!pqc::MLDSA44Verify(bad_hint, msg, pqc::TX_SIGNATURE_CONTEXT, mk.pubkey));
}

