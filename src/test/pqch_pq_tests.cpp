std::string Sha256Hex(const std::vector<unsigned char>& data)
{
    std::array<unsigned char, CSHA256::OUTPUT_SIZE> out;
    CSHA256().Write(data.data(), data.size()).Finalize(out.data());
    return HexStr(out);
}

std::vector<unsigned char> Seed(uint8_t tag)
{
    return std::vector<unsigned char>(pqc::KEY_SEED_SIZE, tag);
}

